"""Measured equivalence classes (`equivalence@2.0`) and the verify-sampling evidence they are regenerated from.

The packaged table is `runtime/data/equivalence.yaml`: per backend, classes whose members are numerics classes
(`numerics_key`), each with its derivation. `scripts/regenerate_equivalence.py` writes it from the
`equivalence-evidence@1.0` records verify sampling leaves in result stores (`classes`, `render`).
"""

import itertools
import json
from collections.abc import Iterable, Mapping
from importlib import resources
from typing import Annotated, Any

import yaml
from pydantic import StringConstraints
from senselab_worker.digest import SHA256_HEX

from senselab_core.kernel._base import Frozen, FrozenMapping, NonEmptyStr, StrMap, value_digest
from senselab_core.kernel.formats import EQUIVALENCE_EVIDENCE_FORMAT, EQUIVALENCE_FORMAT, FormatTag, Formatted
from senselab_core.kernel.identity import Equivalence, ExecutionContext, numerics_key

RETIRED_FORMATS = {"equivalence@1": "regenerate it with scripts/regenerate_equivalence.py from verify evidence"}
"""Retired table formats and the statement that migrates each."""
SAMPLING = "verify-sample"
"""The `value_digest` type over the key digest and both context fingerprints whose first 32 bits sample a hit."""
HEADER = "# Generated by scripts/regenerate_equivalence.py from equivalence-evidence@1.0 records; never hand-edit.\n"


class EquivalenceFormatRetired(ValueError):
    """An equivalence table in a retired format; the message names the migration."""


class _UniqueKeyLoader(yaml.SafeLoader):
    """A YAML loader that refuses a mapping holding one key twice."""


def _unique_mapping(loader: _UniqueKeyLoader, node: yaml.MappingNode, deep: bool = False) -> dict[Any, Any]:
    keys = [loader.construct_object(k, deep=deep) for k, _ in node.value]
    repeated = sorted({str(k) for k in keys if keys.count(k) > 1})
    if repeated:
        raise ValueError(f"{EQUIVALENCE_FORMAT}: duplicate keys {repeated}")
    return loader.construct_mapping(node, deep=deep)


_UniqueKeyLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _unique_mapping)


def _members(where: str, raw: object) -> frozenset[str]:
    if not isinstance(raw, Mapping) or set(raw) != {"numerics", "derivation"}:
        raise ValueError(f"{EQUIVALENCE_FORMAT} class {where} must be a mapping of exactly 'numerics' and 'derivation'")
    derivation, numerics = raw["derivation"], raw["numerics"]
    if not isinstance(derivation, str) or not derivation.strip():
        raise ValueError(f"{EQUIVALENCE_FORMAT} class {where} needs a non-empty derivation")
    if not isinstance(numerics, list) or not all(
        isinstance(n, Mapping) and n and all(isinstance(v, str) for v in n.values()) for n in numerics
    ):
        raise ValueError(f"{EQUIVALENCE_FORMAT} class {where} must list numerics classes, each a mapping of strings")
    members = [numerics_key(n) for n in numerics]
    if len(set(members)) != len(members):
        raise ValueError(f"{EQUIVALENCE_FORMAT} class {where}: duplicate keys, a numerics class listed twice")
    if len(members) < 2:  # noqa: PLR2004 - a class is two or more members by definition, not a tunable
        raise ValueError(f"{EQUIVALENCE_FORMAT} class {where} needs at least two numerics classes")
    return frozenset(members)


def parse_equivalence(text: str) -> Equivalence:
    """Return the read-only table an `equivalence@2.0` document declares.

    The document holds `format` and `backends`, a mapping of backend name to class name to
    `{numerics: [<numerics class>, ...], derivation: ...}`. A class lists at least two numerics classes and a
    non-empty derivation; within a backend a numerics class is in at most one class (it keys its class).

    Raises:
        EquivalenceFormatRetired: the document is `equivalence@1`.
        ValueError: a repeated key at any level, or a document not of that form.
    """
    raw = yaml.load(text, Loader=_UniqueKeyLoader)  # noqa: S506 - a SafeLoader subclass
    found = raw.get("format") if isinstance(raw, dict) else None
    if found in RETIRED_FORMATS:
        raise EquivalenceFormatRetired(f"{found} is retired, read {EQUIVALENCE_FORMAT}: {RETIRED_FORMATS[found]}")
    if not isinstance(raw, dict) or set(raw) != {"format", "backends"} or found != EQUIVALENCE_FORMAT:
        raise ValueError(f"an equivalence table is a mapping of exactly format {EQUIVALENCE_FORMAT!r} and 'backends'")
    backends = raw["backends"]
    if not isinstance(backends, dict) or not all(isinstance(classes, dict) for classes in backends.values()):
        raise ValueError(f"{EQUIVALENCE_FORMAT} backends must map each backend to a mapping of classes")
    table = {}
    for backend, classes in backends.items():
        parsed = {str(name): _members(f"{backend}/{name}", cls) for name, cls in classes.items()}
        shared = sorted(a & b for a, b in itertools.combinations(parsed.values(), 2) if a & b)
        if shared:
            raise ValueError(f"{EQUIVALENCE_FORMAT} backend {backend}: duplicate keys, a numerics class in two classes")
        table[str(backend)] = FrozenMapping(parsed)
    return FrozenMapping(table)


def load_equivalence() -> Equivalence:
    """Return the packaged equivalence table, read-only; pass it, or another measured table, as `equivalence`."""
    text = resources.files("senselab_core.runtime").joinpath("data", "equivalence.yaml").read_text("utf-8")
    return parse_equivalence(text)


EQUIVALENCE: Equivalence = load_equivalence()
"""The packaged measured equivalence classes; the default of `ResultStore(equivalence=)`."""


class EvidenceSide(Frozen):
    """One side of a comparison: the context's fingerprint and its numerics class."""

    fingerprint: Annotated[str, StringConstraints(pattern=SHA256_HEX.pattern)]
    numerics: StrMap

    @classmethod
    def of(cls, context: ExecutionContext) -> "EvidenceSide":
        """Return the side `context` is."""
        return cls(fingerprint=context.fingerprint(), numerics=context.numerics)


class EquivalenceEvidence(Formatted):
    """One verify-sampling comparison of a stored result with its recomputation in the current context.

    `mismatched` names the output paths that differ beyond the backend's tolerance profile, whose canonical
    digest is `tolerance`; `run` is the run id that made the comparison.
    """

    format: FormatTag = EQUIVALENCE_EVIDENCE_FORMAT
    task: NonEmptyStr
    backend: NonEmptyStr
    key: Annotated[str, StringConstraints(pattern=SHA256_HEX.pattern)]
    stored: EvidenceSide
    current: EvidenceSide
    mismatched: tuple[str, ...]
    tolerance: NonEmptyStr
    run: NonEmptyStr

    @property
    def agree(self) -> bool:
        """Whether the recomputation agreed with the stored result within the profile."""
        return not self.mismatched


def sampled(k: float, key: str, stored: ExecutionContext, current: ExecutionContext) -> bool:
    """Return whether a cross-context hit is among the fraction `k` verified, the same answer every time it is asked."""
    if k <= 0:
        return False
    fields = {"key": key, "stored": stored.fingerprint(), "current": current.fingerprint()}
    return int(value_digest(SAMPLING, fields)[:8], 16) < k * 16**8


def split(table: Equivalence, backend: str, a: str, b: str) -> Equivalence:
    """Return `table` with numerics classes `a` and `b` taken out of the class of `backend` holding both.

    The rest of that class stays one class while two or more remain.
    """
    classes = dict(table.get(backend, {}))
    for name, members in classes.items():
        if a in members and b in members:
            rest = members - {a, b}
            if len(rest) >= 2:  # noqa: PLR2004 - a class is two or more members by definition
                classes[name] = rest
            else:
                del classes[name]
            break
    return FrozenMapping({**table, backend: FrozenMapping(classes)})


def _cliques(nodes: set[str], edges: set[frozenset[str]]) -> Iterable[set[str]]:
    """Yield the maximal cliques of the graph (Bron-Kerbosch)."""

    def grow(clique: set[str], candidates: set[str], excluded: set[str]) -> Iterable[set[str]]:
        if not candidates and not excluded:
            yield clique
        for node in sorted(candidates):
            near = {m for m in nodes if frozenset({node, m}) in edges}
            yield from grow(clique | {node}, candidates & near, excluded & near)
            candidates = candidates - {node}
            excluded = excluded | {node}

    yield from grow(set(), set(nodes), set())


def classes(evidence: Iterable[EquivalenceEvidence]) -> dict[str, list[set[str]]]:
    """Return, per backend, the classes `evidence` measures, each a set of `numerics_key`s.

    Two numerics classes are measured equivalent when some comparison of theirs agreed and none disagreed. A class
    is a clique of two or more: every pair in it measured equivalent. Classes are taken largest first (ties by
    their sorted members), each from the numerics classes no earlier class holds. A numerics class that disagreed
    with itself (another env of one numerics class) is in no class.
    """
    agreed: dict[str, set[frozenset[str]]] = {}
    disagreed: dict[str, set[frozenset[str]]] = {}
    nodes: dict[str, set[str]] = {}
    for e in evidence:
        pair = frozenset({numerics_key(e.stored.numerics), numerics_key(e.current.numerics)})
        nodes.setdefault(e.backend, set()).update(pair)
        (agreed if e.agree else disagreed).setdefault(e.backend, set()).add(pair)
    out = {}
    for backend, members in sorted(nodes.items()):
        bad = disagreed.get(backend, set())
        edges = {p for p in agreed.get(backend, set()) if p not in bad and len(p) == 2}  # noqa: PLR2004 - a pair
        left = members - {n for p in bad if len(p) == 1 for n in p}
        found = []
        while True:
            best = min(_cliques(left, edges), key=lambda c: (-len(c), sorted(c)), default=set())
            if len(best) < 2:  # noqa: PLR2004 - a class is two or more
                break
            found.append(best)
            left -= best
        if found:
            out[backend] = found
    return out


def render(evidence: Iterable[EquivalenceEvidence]) -> str:
    """Return the `equivalence@2.0` document `evidence` measures, each class with its derivation."""
    records = list(evidence)
    backends: dict[str, Any] = {}
    for backend, groups in classes(records).items():
        backends[backend] = {}
        for n, group in enumerate(groups):
            used = [
                e
                for e in records
                if e.backend == backend and {numerics_key(e.stored.numerics), numerics_key(e.current.numerics)} <= group
            ]
            derivation = (
                f"verify sampling: {sum(e.agree for e in used)} agreements and"
                f" {sum(not e.agree for e in used)} disagreements over {len({e.key for e in used})} keys,"
                f" runs {', '.join(sorted({e.run for e in used}))},"
                f" tolerance profiles {', '.join(sorted({e.tolerance for e in used}))}"
            )
            numerics = [json.loads(m) for m in sorted(group)]
            backends[backend][f"class-{n}"] = {"numerics": numerics, "derivation": derivation}
    document = {"format": EQUIVALENCE_FORMAT, "backends": backends}
    return HEADER + yaml.safe_dump(document, sort_keys=False)
