from senselab_core.kernel.formats import TOLERANCE_FORMAT

ROOT = Path(__file__).resolve().parents[4]


def _load(name: str, path: Path) -> Any:  # noqa: ANN401
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


tol = _load("generate_tolerance_under_test", ROOT / "scripts" / "generate_tolerance.py")
split_of = tol._harness().split_of


def _ids(split: str, n: int) -> list[str]:
    found: list[str] = []
    k = 0
    while len(found) < n:
        if split_of(f"u{k}") == split:
            found.append(f"u{k}")
        k += 1
    return found


class Stub:
    """A worker whose vector shifts by `batch_shift` when a request holds more than one item."""

    def __init__(self, batch_shift: float = 0.0, repeat_noise: float = 0.0) -> None:
        """Set the shift and the noise."""
        self.batch_shift, self.repeat_noise, self.calls = batch_shift, repeat_noise, 0

    def run(self, items: list[dict[str, Any]], params: dict[str, Any]) -> list[dict[str, Any]]:  # noqa: ARG002
        """Return the vector and a fixed text per item."""
        self.calls += 1
        shift = self.batch_shift if len(items) > 1 else 0.0
        noise = self.repeat_noise * (self.calls % 2)
        return [{"id": i["id"], "outputs": {"embedding": [1.0 + shift + noise, 2.0], "text": "same"}} for i in items]


def _observe(worker: Stub, device: str, ids: list[str], minimum: int = 1) -> Any:  # noqa: ANN401
    return tol.measure(
        worker,
        {i: {"x": i} for i in ids},
        {},
        task="t",
        backend="b",
        device=device,
        stack="s",
        repeats=2,
        sha="a" * 40,
        job="7",
        split_of=split_of,
        minimum=minimum,
    )


@pytest.mark.logic
def test_profile_derived_from_spread_with_derivation(tmp_path: Path) -> None:
    """Spread per axis, tolerance as the largest, findings, and the derivation name SHA, jobs and items."""
    ids = _ids("calibration", 3)
    obs = [_observe(Stub(batch_shift=0.25), "cpu", ids), _observe(Stub(batch_shift=0.25), "cuda", ids)]
    profile = tol.derive(obs, split_of)
    by_path = {f.path: f for f in profile.fields}
    spreads = {s.axis: s.spread for s in by_path["embedding"].spreads}
    assert spreads == {"batch": 0.25, "repeat": 0.0, "device": 0.0}
    assert by_path["embedding"].tolerance == 0.25
    assert by_path["text"].kind == "exact" and by_path["text"].tolerance == 0.0
    assert profile.derivation.shas == ("a" * 40,) and profile.derivation.jobs == ("7",)
    assert profile.derivation.items == tuple(sorted(ids)) and profile.derivation.split == "calibration"
    assert profile.findings == ("embedding: batch spread 0.25 exceeds repeat spread 0",)
    written = yaml.safe_load(tol.write_profile(profile, tmp_path).read_text("utf-8"))
    assert written["format"] == TOLERANCE_FORMAT and written["derivation"]["jobs"] == ["7"]


@pytest.mark.logic
def test_profiles_keyed_by_task_and_backend(tmp_path: Path) -> None:
    """A backend name shared by two tasks gives two profiles, each under a generated-file header."""
    ids = _ids("calibration", 2)
    first = tol.derive([_observe(Stub(), "cpu", ids)], split_of)
    second = first.model_copy(update={"task": "u"})
    a, b = tol.write_profile(first, tmp_path), tol.write_profile(second, tmp_path)
    assert a == tmp_path / "t" / "b.yaml" and b == tmp_path / "u" / "b.yaml"
    assert a.read_text("utf-8").startswith("# Generated by") and yaml.safe_load(b.read_text("utf-8"))["task"] == "u"


@pytest.mark.logic
def test_measure_refuses_fewer_items_than_declared() -> None:
    """A split with fewer items than the declared minimum fails; it never yields an empty or thin profile."""
    with pytest.raises(tol.ToleranceError, match="0 items, 10 are declared"):
        _observe(Stub(), "cpu", [], minimum=10)
    with pytest.raises(tol.ToleranceError, match="2 items, 3 are declared"):
        _observe(Stub(), "cpu", _ids("calibration", 2), minimum=3)
    assert len(_observe(Stub(), "cpu", _ids("calibration", 3), minimum=3).items) == 3


@pytest.mark.logic
def test_every_adapter_items_are_split_by_id(tmp_path: Path) -> None:
    """The gretel adapter's items are cut to the split, calibration and held-out disjoint and together the pool."""
    pa = pytest.importorskip("pyarrow")
    pq = importlib.import_module("pyarrow.parquet")
    rows = {
        "index": list(range(40)),
        "language": ["en"] * 40,
        "generated_text": ["a b c"] * 40,
        "pii_spans": ["[]"] * 40,
    }
    parquet = tmp_path / "gretel.parquet"
    pq.write_table(pa.table(rows), parquet)
    bench = tol._harness().Benchmark(name="g", adapter="gretel_pii", items=40, task="pii_spans", metric="span_f1")
    ids = {s: {i.id for i in tol.split_items(bench, {"f": parquet}, tmp_path, s)} for s in ("calibration", "heldout")}
    assert all(split_of(i) == s for s, found in ids.items() for i in found)
    assert not ids["calibration"] & ids["heldout"] and len(ids["calibration"] | ids["heldout"]) == 40
    assert 0 < len(ids["calibration"]) < 40


@pytest.mark.logic
def test_profile_reads_calibration_only() -> None:
    """A held-out item is refused at measurement and at derivation."""
    held = _ids("heldout", 1)
    with pytest.raises(tol.ToleranceError, match="held-out"):
        _observe(Stub(), "cpu", held)
    obs = _observe(Stub(), "cpu", _ids("calibration", 2))
    relabelled = obs.model_copy(update={"items": (obs.items[0].model_copy(update={"id": held[0]}), *obs.items[1:])})
    with pytest.raises(tol.ToleranceError, match="calibration only"):
        tol.derive([relabelled], split_of)


@pytest.mark.logic
def test_profile_refuses_mixed_backends_and_no_pairs() -> None:
    """Observations of two backends, or none, make no profile."""
    ids = _ids("calibration", 1)
    a = _observe(Stub(), "cpu", ids)
    with pytest.raises(tol.ToleranceError, match="more than one backend"):
        tol.derive([a, a.model_copy(update={"backend": "other"})], split_of)
    with pytest.raises(tol.ToleranceError, match="no observations"):
        tol.derive([], split_of)


@pytest.mark.logic
def test_flatten_leaves_by_path() -> None:
    """Leaves are keyed by dotted path; numbers as float lists, the rest as JSON."""
    flat = tol.flatten({"a": {"b": [1, 2]}, "c": "x", "d": [{"e": 1.5}, "y"]})
    assert flat == {"a.b": [1.0, 2.0], "c": '"x"', "d[0].e": [1.5], "d[1]": '"y"'}


class Diarizer:
    """A worker whose speaker labels swap on every other request; the turns themselves never change."""

    def __init__(self) -> None:
        """Start at the first labelling."""
        self.calls = 0

    def run(self, items: list[dict[str, Any]], params: dict[str, Any]) -> list[dict[str, Any]]:  # noqa: ARG002
        """Return two turns per item, labelled A/B or B/A."""
        self.calls += 1
        labels = ["A", "B"] if self.calls % 2 else ["B", "A"]
        intervals = importlib.import_module("senselab_core.kernel.results").Intervals
        wire = importlib.import_module("senselab_core.kernel.wire")
        reader = importlib.import_module("senselab_core.runtime.audio_io").READER
        turns = intervals(start_ns=[0, 10], end_ns=[10, 15], label=numpy.array(labels), clock_id="c")
        return [{"id": i["id"], "outputs": {"turns": wire.wire_form(turns, reader)}} for i in items]


@pytest.mark.logic
def test_label_permutation_derives_no_spread() -> None:
    """Runs of a real `Intervals` differing only by a permutation of labels derive zero spread on every label."""
    ids = _ids("calibration", 2)
    obs = [_observe(Diarizer(), "cpu", ids), _observe(Diarizer(), "cuda", ids)]  # type: ignore[arg-type]
    labels = [f for f in tol.derive(obs, split_of).fields if f.path.startswith("turns.label")]
    assert [f.path for f in labels] == ["turns.label[*]"]
    assert all(f.tolerance == 0.0 for f in labels)


def _asr_observations(tmp_path: Path, device: str, span: list[float | None]) -> Any:  # noqa: ANN401
    """A real-shaped speech_to_text observation file, read through `load_observations`.

    `timestamps: none` leaves each span `[null]`; the text is a JSON-encoded string.
    """
    runs = [
        {
            "repeat": 0,
            "device": device,
            "stack": "transformers",
            "batch": batch,
            "fields": {
                "transcript.format": '"transcript@1.0"',
                "transcript.segments[0].span": span,
                "transcript.segments[0].text": '"HELLO WORLD"',
                "transcript.segments[0].confidence": [0.9],
            },
        }
        for batch in ("1", "N")
    ]
    document = {
        "format": "tolerance-observations@2.0",
        "flatten": "flatten@2",
        "task": "speech_to_text",
        "backend": "transformers",
        "sha": "a" * 40,
        "job": "7",
        "items": [{"id": _ids("calibration", 1)[0], "split": "calibration", "runs": runs}],
    }
    path = tmp_path / f"{device}-{len(list(tmp_path.iterdir()))}.json"
    path.write_text(json.dumps(document), "utf-8")
    return tol.load_observations(path)


@pytest.mark.logic
def test_real_shaped_asr_observation_validates(tmp_path: Path) -> None:
    """A `[null]` span and a JSON-encoded text string validate, the None kept as None."""
    [item] = _asr_observations(tmp_path, "cpu", [None]).items
    assert item.runs[0].fields["transcript.segments[0].span"] == [None]
    assert item.runs[0].fields["transcript.segments[0].text"] == '"HELLO WORLD"'


@pytest.mark.logic
def test_null_spans_derive_zero_spread(tmp_path: Path) -> None:
    """Two runs whose spans are both `[null]` derive zero spread on the span, with no shape mismatch."""
    obs = [_asr_observations(tmp_path, "cpu", [None]), _asr_observations(tmp_path, "cuda", [None])]
    profile = tol.derive(obs, split_of)
    [span] = [f for f in profile.fields if f.path == "transcript.segments[*].span"]
    assert span.tolerance == 0.0 and span.shape_mismatches == 0 and profile.findings == ()


@pytest.mark.logic
def test_none_against_a_float_disagrees(tmp_path: Path) -> None:
    """A None against a number is a disagreement in derive and in `within`, never a numeric distance."""
    obs = [_asr_observations(tmp_path, "cpu", [None]), _asr_observations(tmp_path, "cuda", [1.5])]
    profile = tol.derive(obs, split_of)
    [span] = [f for f in profile.fields if f.path == "transcript.segments[*].span"]
    assert span.shape_mismatches > 0 and span.tolerance == 0.0
    assert "transcript.segments[*].span: 2 pairs differ in shape" in profile.findings
    loose = tol.ToleranceProfile.model_validate(
        {**profile.model_dump(mode="json"), "fields": [{**span.model_dump(mode="json"), "tolerance": 1e9}]}
    )
    within = importlib.import_module("senselab_core.runtime.tolerance").within
    expected = {"transcript.segments[0].span": [None]}
    assert within(expected, {"transcript.segments[0].span": [1.5]}, loose) == {
        "transcript.segments[0].span": "a None against a number"
    }
    assert within(expected, {"transcript.segments[0].span": [None]}, loose) == {}


def _intervals_output(n: int, labels: list[str] | None = None, shift: int = 0) -> dict[str, Any]:
    """The wire form of a real `Intervals` of `n` 10 ns turns on port `turns`."""
    intervals = importlib.import_module("senselab_core.kernel.results").Intervals
    wire = importlib.import_module("senselab_core.kernel.wire")
    reader = importlib.import_module("senselab_core.runtime.audio_io").READER
    turns = intervals(
        start_ns=[10 * k + shift for k in range(n)],
        end_ns=[10 * k + 10 + shift for k in range(n)],
        label=numpy.array(labels or [f"S{k % 2}" for k in range(n)]),
        clock_id="c",
    )
    return {"turns": wire.wire_form(turns, reader)}


class Turns:
    """A worker returning as many turns as an item's `n`, the same on every run."""

    def run(self, items: list[dict[str, Any]], params: dict[str, Any]) -> list[dict[str, Any]]:  # noqa: ARG002
        """Return `n` turns per item."""
        return [{"id": i["id"], "outputs": _intervals_output(i["inputs"]["n"])} for i in items]


def _turns_profile() -> Any:  # noqa: ANN401
    """A profile derived on cpu and cuda from calibration items of 1 and 2 turns."""
    ids = _ids("calibration", 2)
    items = {ids[0]: {"n": 1}, ids[1]: {"n": 2}}
    common = {"task": "diarize", "backend": "b", "stack": "s", "repeats": 1, "sha": "a" * 40, "job": "7"}
    obs = [tol.measure(Turns(), items, {}, device=d, split_of=split_of, **common) for d in ("cpu", "cuda")]
    return tol.derive(obs, split_of)


@pytest.mark.logic
def test_three_turns_verify_against_a_profile_of_one_and_two() -> None:
    """A held-out output with more turns than any calibration item is judged by the index-free fields."""
    profile = _turns_profile()
    assert {f.path for f in profile.fields} >= {"turns.label[*]", "turns.start_ns", "turns.end_ns"}
    within = importlib.import_module("senselab_core.runtime.tolerance").within
    three = tol.flatten(_intervals_output(3))
    assert within(three, tol.flatten(_intervals_output(3, ["T1", "T0", "T1"])), profile) == {}
    assert list(within(three, tol.flatten(_intervals_output(3, shift=1)), profile)) == [
        "turns.end_ns",
        "turns.start_ns",
    ]


@pytest.mark.logic
def test_identical_single_turn_outputs_agree() -> None:
    """Identical cpu and cuda outputs of one turn (`SPEAKER_00`, same times) pass `within`."""
    within = importlib.import_module("senselab_core.runtime.tolerance").within
    one = tol.flatten(_intervals_output(1, ["SPEAKER_00"]))
    assert within(one, tol.flatten(_intervals_output(1, ["SPEAKER_00"])), _turns_profile()) == {}


@pytest.mark.logic
def test_derive_pools_spreads_over_indices() -> None:
    """Every index of a path feeds one index-free field, its tolerance the largest spread over all of them."""
    a = {"seg[0].v": [1.0], "seg[1].v": [5.0], "seg[1].t": '"x"'}
    b = {"seg[0].v": [1.5], "seg[1].v": [7.0], "seg[1].t": '"x"'}
    runs = [tol.Run(repeat=0, device=d, stack="s", batch="1", fields=f) for d, f in (("cpu", a), ("cuda", b))]
    item = tol.ObservedItem(id=_ids("calibration", 1)[0], split="calibration", runs=tuple(runs))
    obs = tol.Observations(flatten="flatten@2", task="t", backend="b", sha="s", job="j", items=(item,))
    fields = {f.path: f for f in tol.derive([obs], split_of).fields}
    assert set(fields) == {"seg[*].v", "seg[*].t"}
    assert fields["seg[*].v"].tolerance == 2.0 and fields["seg[*].v"].spreads[0].pairs == 2


def _write(tmp_path: Path, document: dict[str, Any]) -> Path:
    path = tmp_path / "old.json"
    path.write_text(json.dumps(document), "utf-8")
    return path


def _old(fields: dict[str, Any], **override: Any) -> dict[str, Any]:  # noqa: ANN401
    run = {"repeat": 0, "device": "cpu", "stack": "s", "batch": "1", "fields": fields}
    item = {"id": "i", "split": "calibration", "runs": [run]}
    return {
        "format": "tolerance-observations@1.0",
        "task": "t",
        "backend": "b",
        "sha": "s",
        "job": "j",
        "items": [item],
        **override,
    }


@pytest.mark.logic
@pytest.mark.parametrize(
    "document",
    [
        _old({"embedding.vector": [0.5]}),
        _old({"turns.label": json.dumps("['SPEAKER_00' 'SPEAKER_01']")}),
        _old({}, format="tolerance-observations@2.0", flatten="flatten@1"),
        _old({}, format="tolerance-observations@2.0"),
        _old({}, format="tolerance-observations@3.0", flatten="flatten@2"),
    ],
    ids=["observations@1", "observations@1-repr", "older-flatten", "no-flatten", "other-format"],
)
def test_stale_observations_refused(tmp_path: Path, document: dict[str, Any]) -> None:
    """Every observation file not of the current format and flatten is refused by name, never upgraded."""
    path = _write(tmp_path, document)
    with pytest.raises(tol.ToleranceError, match="re-measure it") as raised:
        tol.load_observations(path)
    assert str(path) in str(raised.value)
