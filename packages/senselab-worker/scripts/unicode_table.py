"""Generate `senselab_worker/data/unicode-assigned.txt`, the code points whose text canonical encoders normalise.

Run under the worker's floor interpreter, whose `unicodedata` is the Unicode version the table names:

    uv run --no-project --python 3.10 python packages/senselab-worker/scripts/unicode_table.py

The derivation is in ADR-006 ("Canonical text").
"""

import hashlib
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType

TABLE = Path(__file__).resolve().parents[1] / "src" / "senselab_worker" / "data" / "unicode-assigned.txt"
FLOOR_UNICODE = "13.0.0"
_REFUSED_CATEGORIES = ("Cn", "Cs")
_LOW_PROBE = "̴"
"""A mark of combining class 1: any later mark of a higher class sorts before it."""
_HIGH_PROBE = "ͅ"
"""A mark of combining class 240: any earlier mark of a lower nonzero class sorts after it."""


@dataclass(frozen=True)
class Table:
    """What the table file holds."""

    version: str
    fingerprint: str
    ranges: list[tuple[int, int]]
    pairs: list[tuple[int, int, int]]
    """Canonical composition pairs of the floor: `(first, second, composite)`."""
    marks: list[int]
    """One mark per nonzero canonical combining class of the floor: the reference order."""


def allowed(db: ModuleType = unicodedata) -> list[tuple[int, int]]:
    """Return the inclusive ranges of code points `db` assigns, surrogates excluded."""
    ranges: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if db.category(chr(cp)) in _REFUSED_CATEGORIES:
            continue
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return ranges


def _code_points(ranges: list[tuple[int, int]]) -> list[int]:
    return [cp for start, end in ranges for cp in range(start, end + 1)]


def composition_pairs(ranges: list[tuple[int, int]], db: ModuleType = unicodedata) -> list[tuple[int, int, int]]:
    """Return the floor's primary composites as `(first, second, composite)`, read once from its database."""
    pairs = []
    for cp in _code_points(ranges):
        mapping = db.decomposition(chr(cp)).split()
        if len(mapping) == 2 and not mapping[0].startswith("<"):
            first, second = (int(part, 16) for part in mapping)
            if db.normalize("NFC", chr(first) + chr(second)) == chr(cp):
                pairs.append((first, second, cp))
    return pairs


def reference_marks(ranges: list[tuple[int, int]], db: ModuleType = unicodedata) -> list[int]:
    """Return the first allowed code point of each nonzero canonical combining class of the floor."""
    marks: dict[int, int] = {}
    for cp in _code_points(ranges):
        marks.setdefault(db.combining(chr(cp)), cp)
    return [marks[ccc] for ccc in sorted(marks) if ccc]


def _hex(text: str) -> str:
    return " ".join(f"{ord(c):X}" for c in text)


def nfc_fingerprint(table: "Table", db: ModuleType = unicodedata) -> str:
    """Return the sha256 of what normalisation does under `db` over the table's text.

    It covers the NFD and NFC of every allowed code point, the NFC of every composition pair, and,
    for every code point whose NFD reorders against a class-1 or class-240 probe mark, its NFD before
    each reference mark. Only normalisation outputs are hashed, never database metadata.
    """
    digest = hashlib.sha256()
    for cp in _code_points(table.ranges):
        ch = chr(cp)
        nfd = db.normalize("NFD", ch)
        digest.update(f"{cp:X};{_hex(nfd)};{_hex(db.normalize('NFC', ch))}\n".encode("ascii"))
        reorders = db.normalize("NFD", ch + _LOW_PROBE) != nfd + _LOW_PROBE
        reorders = reorders or db.normalize("NFD", _HIGH_PROBE + ch) != _HIGH_PROBE + nfd
        if reorders:
            order = ";".join(_hex(db.normalize("NFD", ch + chr(mark))) for mark in table.marks)
            digest.update(f"O;{cp:X};{order}\n".encode("ascii"))
    for first, second, _ in table.pairs:
        nfc = _hex(db.normalize("NFC", chr(first) + chr(second)))
        digest.update(f"P;{first:X};{second:X};{nfc}\n".encode("ascii"))
    return digest.hexdigest()


def generate(db: ModuleType = unicodedata) -> Table:
    """Return the table `db` gives."""
    ranges = allowed(db)
    draft = Table(db.unidata_version, "", ranges, composition_pairs(ranges, db), reference_marks(ranges, db))
    return Table(draft.version, nfc_fingerprint(draft, db), ranges, draft.pairs, draft.marks)


def render(table: Table) -> str:
    """Return the table file's text."""
    head = [
        f"# Code points assigned in Unicode {table.version}, surrogates excluded: text holding only these is normalised.",
        "# Generated by packages/senselab-worker/scripts/unicode_table.py under Python 3.10; do not edit.",
        f"# derivation: every code point whose general category in unicodedata {table.version} is neither Cn nor Cs",
        "# (ADR-006). `pair` lines are its canonical composition pairs and `marks` one mark per nonzero combining",
        "# class, both read once from that database for the fingerprint.",
        f"unicode_version {table.version}",
        f"nfc_fingerprint {table.fingerprint}",
        "marks " + " ".join(f"{m:04X}" for m in table.marks),
    ]
    pairs = [f"pair {a:04X} {b:04X} {c:04X}" for a, b, c in table.pairs]
    return "\n".join(head + [f"{a:04X} {b:04X}" for a, b in table.ranges] + pairs) + "\n"


def read(text: str) -> Table:
    """Parse the table file's text."""
    header: dict[str, list[str]] = {}
    ranges: list[tuple[int, int]] = []
    pairs: list[tuple[int, int, int]] = []
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        key, *rest = line.split(" ")
        if key == "pair":
            a, b, c = (int(part, 16) for part in rest)
            pairs.append((a, b, c))
        elif key in ("unicode_version", "nfc_fingerprint", "marks"):
            header[key] = rest
        else:
            ranges.append((int(key, 16), int(rest[0], 16)))
    marks = [int(m, 16) for m in header["marks"]]
    return Table(header["unicode_version"][0], header["nfc_fingerprint"][0], ranges, pairs, marks)


def main() -> int:
    """Write the table, refusing to run under any Unicode version but the floor's."""
    if unicodedata.unidata_version != FLOOR_UNICODE:
        print(f"run under Python 3.10 (Unicode {FLOOR_UNICODE}), not {unicodedata.unidata_version}", file=sys.stderr)
        return 2
    TABLE.parent.mkdir(exist_ok=True)
    TABLE.write_text(render(generate()), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
