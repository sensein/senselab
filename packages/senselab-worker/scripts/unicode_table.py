"""Generate `senselab_worker/data/unicode-assigned.txt`, the code points canonical text may hold.

Run under the worker's floor interpreter, whose `unicodedata` is the Unicode version the table names:

    uv run --no-project --python 3.10 python packages/senselab-worker/scripts/unicode_table.py

The derivation is in ADR-006 ("Canonical text").
"""

import hashlib
import sys
import unicodedata
from pathlib import Path
from types import ModuleType

TABLE = Path(__file__).resolve().parents[1] / "src" / "senselab_worker" / "data" / "unicode-assigned.txt"
FLOOR_UNICODE = "13.0.0"
_REFUSED_CATEGORIES = ("Cn", "Cs")


def allowed(db: ModuleType = unicodedata) -> list[tuple[int, int]]:
    """Return the inclusive ranges of code points `db` assigns, surrogates excluded."""
    ranges: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if db.category(chr(cp)) in _REFUSED_CATEGORIES:
            continue
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return ranges


def nfc_fingerprint(ranges: list[tuple[int, int]], db: ModuleType = unicodedata) -> str:
    """Return the sha256 over every code point in `ranges` of what NFC reads from `db` for it.

    Each line is the code point, its canonical combining class, its decomposition mapping, and its
    NFD and NFC, so two databases with one fingerprint normalise every string over `ranges` alike.
    """
    digest = hashlib.sha256()
    for start, end in ranges:
        for cp in range(start, end + 1):
            ch = chr(cp)
            nfd = " ".join(f"{ord(c):X}" for c in db.normalize("NFD", ch))
            nfc = " ".join(f"{ord(c):X}" for c in db.normalize("NFC", ch))
            digest.update(f"{cp:X};{db.combining(ch)};{db.decomposition(ch)};{nfd};{nfc}\n".encode("ascii"))
    return digest.hexdigest()


def render(ranges: list[tuple[int, int]], fingerprint: str, version: str) -> str:
    """Return the table file's text."""
    head = [
        f"# Code points assigned in Unicode {version}, surrogates excluded: the text canonical encoders accept.",
        "# Generated by packages/senselab-worker/scripts/unicode_table.py under Python 3.10; do not edit.",
        "# derivation: every code point whose general category in unicodedata "
        f"{version} is neither Cn nor Cs (ADR-006).",
        f"unicode_version {version}",
        f"nfc_fingerprint {fingerprint}",
    ]
    return "\n".join(head + [f"{a:04X} {b:04X}" for a, b in ranges]) + "\n"


def main() -> int:
    """Write the table, refusing to run under any Unicode version but the floor's."""
    if unicodedata.unidata_version != FLOOR_UNICODE:
        print(f"run under Python 3.10 (Unicode {FLOOR_UNICODE}), not {unicodedata.unidata_version}", file=sys.stderr)
        return 2
    ranges = allowed()
    TABLE.parent.mkdir(exist_ok=True)
    TABLE.write_text(render(ranges, nfc_fingerprint(ranges), FLOOR_UNICODE), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
