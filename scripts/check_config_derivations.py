"""Fail when a data file carries an inline derivation, or a key of one has no section in config-derivations.md.

Every YAML file git tracks under a ``data/`` directory of ``packages/`` or ``scripts/`` holds values only; why each
top-level key has its value is a ``### <key>`` section under the file's ``## <path>`` section of config-derivations.md
(P-17). A ``derivation`` or ``derivations`` key at any depth is refused. ``INLINE_EXEMPT`` and ``SECTION_EXEMPT``
name the files outside one check or the other, each with its reason. Without config-derivations.md in the tree (a code branch), only the inline keys are checked.

Usage::

    uv run python scripts/check_config_derivations.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "specs" / "20261030-140022-senselab-2x-api" / "config-derivations.md"
DATA = re.compile(r"^(packages|scripts)/(.+/)?data/.+\.yaml$")
_CORE = "packages/senselab-core/src/senselab_core/runtime/data/"
_SENSELAB = "packages/senselab/src/senselab/data/"
INLINE_EXEMPT = {
    f"{_CORE}spdx_licenses.yaml": "one derivation per unnamed license group; moving them needs named groups",
}
SECTION_EXEMPT = {
    **INLINE_EXEMPT,
    f"{_CORE}profiles/laptop.yaml": "sectioned by profile and key, under ## laptop",
    f"{_CORE}profiles/orcd.yaml": "sectioned by profile and key, under ## orcd",
    "packages/senselab-core/tests/data/test_slack.yaml": "sectioned under ## test_slack",
    f"{_CORE}comparison.yaml": "how each kernel type's fields compare; the thresholds it names are run_config.yaml's",
    f"{_CORE}weights.yaml": "measured digests of weight files, not chosen values",
    f"{_SENSELAB}catalogue.yaml": "generated from pinned hub metadata, not chosen values",
    f"{_SENSELAB}env_licenses.yaml": "generated by scripts/check_licenses.py from installed metadata",
    f"{_SENSELAB}profiles/pii_spans.yaml": "derivation still in a # comment block, not yet sectioned",
    f"{_SENSELAB}server_settings/pii_spans_vllm.yaml": "derivation still in a # comment block, not yet sectioned",
    "scripts/data/invariants.yaml": "an exception list; each entry carries its own reason",
}
INLINE = frozenset({"derivation", "derivations"})


def inline(value: Any, where: str = "") -> list[str]:
    """The dotted path of every ``derivation`` or ``derivations`` key in `value`."""
    if isinstance(value, dict):
        found = [f"{where}{k}" for k in value if k in INLINE]
        return found + [p for k, v in value.items() for p in inline(v, f"{where}{k}.")]
    if isinstance(value, list):
        return [p for i, v in enumerate(value) for p in inline(v, f"{where}{i}.")]
    return []


def sections(spec: str) -> dict[str, set[str]]:
    """The ``### `` headings under each ``## `` heading of `spec`."""
    out: dict[str, set[str]] = {}
    current = None
    for line in spec.splitlines():
        if line.startswith("## "):
            current = out.setdefault(line[3:].strip(), set())
        elif line.startswith("### ") and current is not None:
            current.add(line[4:].strip())
    return out


def problems(path: str, raw: Any, spec: dict[str, set[str]] | None) -> list[str]:
    """Why the config at `path` (parsed as `raw`) fails: inline derivations, and keys without a section."""
    out = [f"{path}: {key} is inline; move it to config-derivations.md under ## {path}" for key in inline(raw)]
    if spec is not None and isinstance(raw, dict):
        have = spec.get(path, set())
        out += [
            f"{path}: {key} has no '### {key}' under '## {path}'" for key in raw if key != "format" and key not in have
        ]
    return out


def tracked_data(root: Path = ROOT) -> list[str]:
    """Every YAML file git tracks under a ``data/`` directory of ``packages/`` or ``scripts/``."""
    out = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "packages", "scripts"], capture_output=True, check=True
    )
    return [p for p in out.stdout.decode().split("\0") if DATA.match(p)]


def findings(root: Path = ROOT, spec_path: Path = SPEC) -> list[str]:
    """Every problem of the tracked data files of `root` against `spec_path`, and each stale exemption."""
    spec = sections(spec_path.read_text()) if spec_path.is_file() else None
    tracked = tracked_data(root)
    found = [f"{path} is exempt but not tracked; remove it" for path in sorted(set(SECTION_EXEMPT) - set(tracked))]
    for path in tracked:
        if path in INLINE_EXEMPT:
            continue
        exempt = path in SECTION_EXEMPT
        found += problems(path, yaml.safe_load((root / path).read_text()), None if exempt else spec)
    return found


def main(root: Path = ROOT, spec_path: Path = SPEC) -> int:
    """Check the tracked data files of `root`; print the problems; return 1 if any."""
    if not spec_path.is_file():
        print(f"{spec_path.name} is not in this tree: section check skipped")
    found = findings(root, spec_path)
    for line in found:
        print(line)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
