"""Measure a backend's outputs across contexts on the calibration split and derive its tolerance profile.

`measure` runs one backend's worker over the calibration items of a suite benchmark (default suite `tolerance`), in one device and stack: each
item alone and all items in one batch, each `--repeats` times, and writes `tolerance-observations@1.0`.
`generate` reads the observations of every context of one backend and writes `tolerance@1.0`: per output field,
the spread across each axis (repeat, device, batch, stack). Held-out items are refused; a profile is never edited.
"""

import argparse
import importlib.util
import itertools
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from types import ModuleType
from typing import Any, Protocol

import yaml
from senselab_core.kernel._base import Frozen, NonEmptyStr
from senselab_core.kernel.formats import TOLERANCE_OBSERVATIONS_FORMAT, FormatTag, Formatted
from senselab_core.runtime.tolerance import (
    AxisSpread,
    Derivation,
    FieldTolerance,
    ToleranceProfile,
    Fields,
    Value,
    flatten,
    numeric_gap,
    relabel_turns,
    tolerance_profile_path,
)

ROOT = Path(__file__).resolve().parents[1]
AXES = ("repeat", "device", "batch", "stack")
CALIBRATION = "calibration"
SINGLE, MANY = "1", "N"
HEADER = "# Generated by scripts/generate_tolerance.py from the observations named in `derivation`; never hand-edit.\n"


class ToleranceError(ValueError):
    """Observations that cannot make a profile: a held-out item, mixed backends, or no pair of runs."""


class Run(Frozen):
    """One run of one item: the context it ran in and its flattened output fields."""

    repeat: int
    device: NonEmptyStr
    stack: NonEmptyStr
    batch: NonEmptyStr
    fields: Fields


class ObservedItem(Frozen):
    """An item's id, its split and its runs."""

    id: NonEmptyStr
    split: NonEmptyStr
    runs: tuple[Run, ...]


class Observations(Formatted):
    """What one measurement job saw: the SHA and job it ran at and, per item, every run."""

    format: FormatTag = TOLERANCE_OBSERVATIONS_FORMAT
    task: NonEmptyStr
    backend: NonEmptyStr
    sha: NonEmptyStr
    job: NonEmptyStr
    backend_params: dict[str, Any] = {}
    items: tuple[ObservedItem, ...]


class Runner(Protocol):
    """What `measure` needs of a worker."""

    def run(self, items: list[dict[str, Any]], params: dict[str, Any]) -> list[dict[str, Any]]:
        """Run one request and return one result per item."""
        ...


def _harness() -> ModuleType:
    spec = importlib.util.spec_from_file_location("benchmark_harness", ROOT / "benchmarks" / "harness.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def measure(  # noqa: PLR0913 - what one measurement job fixes
    worker: Runner,
    items: Mapping[str, Mapping[str, Any]],
    params: dict[str, Any],
    *,
    task: str,
    backend: str,
    device: str,
    stack: str,
    repeats: int,
    sha: str,
    job: str,
    backend_params: Mapping[str, Any] | None = None,
    split_of: Any,
    minimum: int = 1,
) -> Observations:
    """Run the calibration items of `items` alone and in one batch, `repeats` times each.

    An item the worker fails on has no run.

    Raises:
        ToleranceError: `items` holds a held-out item, or fewer than `minimum` items have a run.
    """
    if len(items) < minimum:
        raise ToleranceError(f"{task}/{backend}: the calibration split has {len(items)} items, {minimum} are declared")
    held = sorted(i for i in items if split_of(i) != CALIBRATION)
    if held:
        raise ToleranceError(f"held-out items cannot be measured for a profile: {held}")
    runs: dict[str, list[Run]] = {i: [] for i in items}
    for repeat in range(repeats):
        for batch, groups in ((SINGLE, [[i] for i in items]), (MANY, [list(items)])):
            for group in groups:
                results = worker.run([{"id": i, "inputs": items[i]} for i in group], params)
                for result in results:
                    if "outputs" in result:
                        fields = flatten(result["outputs"])
                        runs[result["id"]].append(
                            Run(repeat=repeat, device=device, stack=stack, batch=batch, fields=fields)
                        )
    observed = tuple(ObservedItem(id=i, split=CALIBRATION, runs=tuple(r)) for i, r in runs.items() if r)
    if len(observed) < minimum:
        raise ToleranceError(f"{task}/{backend}: {len(observed)} of {len(items)} items ran, {minimum} are declared")
    return Observations(
        task=task, backend=backend, sha=sha, job=job, backend_params=dict(backend_params or {}), items=observed
    )


def _spread(a: Value, b: Value) -> tuple[float, bool]:
    """Return (spread, shapes differ): the largest absolute difference, or 0/1 for strings.

    Two numeric leaves differ in shape when their lengths differ or a None stands against a number (`numeric_gap`).
    """
    if isinstance(a, str) or isinstance(b, str):
        return float(a != b), False
    gap = numeric_gap(a, b) if len(a) == len(b) else None
    return (0.0, True) if gap is None else (gap, False)


def derive(observations: Sequence[Observations], split_of: Any) -> ToleranceProfile:
    """Return the profile of the observations of one backend, every item checked to be a calibration item.

    Speaker turns of two runs are compared under `relabel_turns`.

    Raises:
        ToleranceError: an item is held out or was not recorded as calibration, the observations are of
            different backends, or no two runs differ along exactly one axis.
    """
    if not observations:
        raise ToleranceError("no observations")
    task, backend = observations[0].task, observations[0].backend
    if any((o.task, o.backend) != (task, backend) for o in observations):
        raise ToleranceError("observations of more than one backend")
    spreads: dict[str, dict[str, list[float]]] = {}
    kinds: dict[str, str] = {}
    shapes: dict[str, int] = {}
    ids: set[str] = set()
    contexts: set[str] = set()
    for obs in observations:
        for item in obs.items:
            if item.split != CALIBRATION or split_of(item.id) != CALIBRATION:
                raise ToleranceError(f"item {item.id!r} is not a calibration item; profiles read calibration only")
            ids.add(item.id)
            contexts.update(f"{r.device}/{r.stack}/batch-{r.batch}" for r in item.runs)
    for item_id in ids:
        runs = [r for obs in observations for item in obs.items if item.id == item_id for r in item.runs]
        for a, b in itertools.combinations(runs, 2):
            differing = [x for x in AXES if getattr(a, x) != getattr(b, x)]
            if len(differing) != 1:
                continue
            b_fields = relabel_turns(a.fields, b.fields)
            for path in a.fields.keys() & b_fields.keys():
                value, bad_shape = _spread(a.fields[path], b_fields[path])
                kinds[path] = "exact" if isinstance(a.fields[path], str) else "numeric"
                shapes[path] = shapes.get(path, 0) + bad_shape
                spreads.setdefault(path, {}).setdefault(differing[0], []).append(value)
    if not spreads:
        raise ToleranceError("no two runs of an item differ along exactly one axis")
    fields = tuple(
        FieldTolerance(
            path=path,
            kind=kinds[path],
            spreads=tuple(AxisSpread(axis=a, spread=max(v), pairs=len(v)) for a, v in sorted(by_axis.items())),
            tolerance=max(max(v) for v in by_axis.values()),
            shape_mismatches=shapes[path],
        )
        for path, by_axis in sorted(spreads.items())
    )
    return ToleranceProfile(
        task=task,
        backend=backend,
        derivation=Derivation(
            shas=tuple(sorted({o.sha for o in observations})),
            jobs=tuple(sorted({o.job for o in observations})),
            split=CALIBRATION,
            items=tuple(sorted(ids)),
            contexts=tuple(sorted(contexts)),
        ),
        fields=fields,
        findings=_findings(fields),
    )


def _findings(fields: Sequence[FieldTolerance]) -> tuple[str, ...]:
    """State, per field, each axis whose spread exceeds the repeat spread (none measured counts as 0)."""
    out = []
    for f in fields:
        by_axis = {s.axis: s.spread for s in f.spreads}
        base = by_axis.get("repeat", 0.0)
        for axis, value in by_axis.items():
            if axis != "repeat" and value > base:
                out.append(f"{f.path}: {axis} spread {value:g} exceeds repeat spread {base:g}")
        if f.shape_mismatches:
            out.append(f"{f.path}: {f.shape_mismatches} pairs differ in shape")
    return tuple(out)


def write_profile(profile: ToleranceProfile, out: Path) -> Path:
    """Write `<out>/<task>/<backend>.yaml`."""
    path = tolerance_profile_path(out, profile.task, profile.backend)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + yaml.safe_dump(json.loads(profile.model_dump_json()), sort_keys=False), "utf-8")
    return path


def _wired(port: str, port_type: str, value: object) -> object:
    """Return the wire form of an item input as the call path binds it."""
    from senselab_core.kernel.wire import wire_form  # noqa: PLC0415 - only a real measurement needs the runtime
    from senselab_core.runtime.audio_io import READER  # noqa: PLC0415
    from senselab_core.runtime.call import bind_input  # noqa: PLC0415

    bound = bind_input(port, port_type, value)[1]
    return wire_form(bound, READER) if isinstance(bound, Frozen) else bound


def resolve(task: str, backend_name: str) -> tuple[Any, Any]:
    """Return (task spec, backend spec), importing `senselab` first: that import registers the packaged tasks."""
    importlib.import_module("senselab")
    from senselab_core.runtime.call import packaged  # noqa: PLC0415 - needs the registered runtime

    backend = next(b for b in packaged().registry.backends(task) if b.name == backend_name)
    return packaged().registry.spec(task), backend


def load_items(suite: Path, benchmark: str, data_cache: Path, work: Path, split: str) -> tuple[Any, list[Any]]:
    """Return (benchmark, its adapter items of `split`), the data fetched into `data_cache`, files under `work`."""
    from senselab_core.runtime.fetch import DataManifest, fetch  # noqa: PLC0415 - only a real run needs the runtime

    [bench] = [b for b in _harness().Suite.load(suite).benchmarks if b.name == benchmark]
    files = (
        {}
        if bench.manifest is None
        else fetch(
            DataManifest.load(ROOT / "benchmarks" / "manifests" / f"{bench.manifest}.yaml"), cache_root=data_cache
        )
    )
    return bench, split_items(bench, files, work, split)


def split_items(bench: Any, files: Mapping[str, Path], work: Path, split: str) -> list[Any]:  # noqa: ANN401
    """Return the items of `bench`'s adapter, of any adapter, that belong to `split`."""
    harness = _harness()
    items = harness.ADAPTERS[bench.adapter]().items(files, bench.items, work, bench.max_seconds)
    return [i for i in items if harness.split_of(i.id) == split]


def prepare(  # noqa: PLR0913 - what picks one benchmark's items and params
    suite: Path,
    benchmark: str,
    backend_name: str,
    backend_params: Mapping[str, Any],
    data_cache: Path,
    work: Path,
    split: str,
) -> tuple[Any, Any, dict[str, dict[str, object]], dict[str, Any]]:
    """Return (benchmark, backend spec, wired inputs of the `split` items by id, call params) for one benchmark."""
    bench, items = load_items(suite, benchmark, data_cache, work, split)
    spec, backend = resolve(bench.task, backend_name)
    wired = {i.id: {p: _wired(p, spec.inputs[p], v) for p, v in i.inputs.items()} for i in items}
    params = {
        **spec.params.model_validate(bench.params).model_dump(mode="json"),
        "backend_params": backend.params.model_validate(backend_params).model_dump(mode="json"),
    }
    return bench, backend, wired, params


def _measure_cli(args: argparse.Namespace) -> None:
    """Run `args.backend` over the calibration items of benchmark `args.benchmark` of `args.suite`."""
    from senselab_core.runtime.profiles import ExecutionProfile  # noqa: PLC0415 - only a real run needs the runtime
    from senselab_core.testing.workers import RealWorkers  # noqa: PLC0415

    bench, backend, wired, params = prepare(
        args.suite, args.benchmark, args.backend, args.backend_params, args.data_cache, args.work, CALIBRATION
    )
    workers = RealWorkers(ExecutionProfile.load(args.execution))
    try:
        observations = measure(
            workers(bench.task, args.backend),
            wired,
            params,
            task=bench.task,
            backend=args.backend,
            device=workers.device,
            stack=backend.stack + "".join(f" {k}={v}" for k, v in sorted(args.backend_params.items())),
            repeats=args.repeats,
            sha=args.sha,
            job=args.job,
            backend_params=params["backend_params"],
            split_of=_harness().split_of,
            minimum=bench.min_calibration,
        )
    finally:
        workers.close()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(observations.model_dump_json(indent=1), "utf-8")


def _generate_cli(args: argparse.Namespace) -> None:
    observations = [Observations.model_validate_json(p.read_text("utf-8")) for p in args.observations]
    print(write_profile(derive(observations, _harness().split_of), args.out))


def main(argv: Sequence[str] | None = None) -> None:
    """Command line: `measure` one context, `generate` a profile from every context's observations."""
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(required=True)
    m = sub.add_parser("measure")
    m.add_argument("--suite", type=Path, default=ROOT / "benchmarks" / "suites" / "tolerance.yaml")
    m.add_argument("--benchmark", required=True)
    m.add_argument("--backend", required=True)
    m.add_argument("--execution", default="orcd")
    m.add_argument(
        "--backend-params", type=json.loads, default={}, help="JSON of the backend's params, e.g. the engine"
    )
    m.add_argument("--repeats", type=int, default=3)
    m.add_argument("--sha", required=True)
    m.add_argument("--job", required=True)
    m.add_argument("--data-cache", type=Path, required=True)
    m.add_argument("--work", type=Path, required=True)
    m.add_argument("--out", type=Path, required=True)
    m.set_defaults(func=_measure_cli)
    g = sub.add_parser("generate")
    g.add_argument("observations", type=Path, nargs="+")
    g.add_argument("--out", type=Path, default=ROOT / "packages/senselab/src/senselab/data/tolerance")
    g.set_defaults(func=_generate_cli)
    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
