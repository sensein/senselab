"""Behavioural tests for the differential over a replayed store.

Nothing here is faked. Each fixture is a real :class:`ProvStore` written, read back under the
replay's own run id, retired with :func:`retire_decisions` and written again, which is the exact
sequence the replay driver performs. The properties asserted are the ones the differential rests
on: that the two passes are recoverable from the invalidation edges alone, that a decision which
did not move reads as identical, that a field the replay added is not a move, and that nothing the
store holds as text reaches a row.

``specs/20260922-replay-decisions-over-a-finished-corpus/differential.md`` is the design.
"""

